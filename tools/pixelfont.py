FONT = {}
for _src in (_UPPER, _LOWER, _DIGITS, _PUNCT):
    for _ch, _bits in _src.items():
        assert len(_bits) == 35, (_ch, len(_bits))
        FONT[_ch] = [_bits[r * 5:(r + 1) * 5] for r in range(7)]

GLYPH_W, GLYPH_H, ADVANCE = 5, 7, 6


def rect(x, y, w, h, fill):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}"/>'


def text_width(s, scale=1):
    """Advance width of a string, without the trailing inter-glyph gap."""
    return (len(s) * ADVANCE - 1) * scale if s else 0


def text(s, x, y, scale=1, fill="#E8E8F0"):
    """Emit a string as merged horizontal runs of rects -- far fewer nodes
    than one rect per lit pixel, and identical output."""
    out = []
    cx = x
    for ch in s:
        glyph = FONT.get(ch, FONT["?"])
        for r, row in enumerate(glyph):
            start = None
            for c, px in enumerate(row + "."):
                if px == ON and start is None:
                    start = c
                elif px != ON and start is not None:
                    out.append(rect(cx + start * scale, y + r * scale,
                                    (c - start) * scale, scale, fill))
                    start = None
        cx += ADVANCE * scale
    return "".join(out)


def text_centered(s, cx, y, scale=1, fill="#E8E8F0"):
    return text(s, cx - text_width(s, scale) // 2, y, scale, fill)


def sprite(art, palette, x, y, scale=1):
    """Render a bitmap given as a list of equal-length strings, where each
    character indexes into `palette`. '.' is transparent."""
    out = []
    for r, row in enumerate(art):
        start, cur = None, None
        for c, key in enumerate(row + "."):
            colour = palette.get(key)
            if colour != cur:
                if cur is not None and start is not None:
                    out.append(rect(x + start * scale, y + r * scale,
                                    (c - start) * scale, scale, cur))
                start, cur = (c, colour) if colour else (None, None)
        # trailing run closed by the sentinel '.' above
    return "".join(out)
